export function exportToM3U(channels: Channel[]): string {
  let content = '#EXTM3U\n# Generated by OpenTV World - Trinh Phat Tivi Toan Cau Ban Quyen Mo\n';
  channels.forEach((ch) => {
    const stream = ch.streamUrl || ch.embedUrl || '';
    content += `#EXTINF:-1 tvg-id="${ch.id}" tvg-name="${ch.name}" tvg-country="${ch.country}" group-title="${ch.category.toUpperCase()} - ${ch.country}",${ch.name}\n`;
    content += `${stream}\n`;
  });
  return content;
}

export function parseM3U(content: string): Partial<Channel>[] {
  const lines = content.split('\n');
  const results: Partial<Channel>[] = [];
  let currentInfo: { name: string; id?: string; group?: string; country?: string } | null = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    if (line.startsWith('#EXTINF:')) {
      const nameMatch = line.match(/,(.+)$/);
      const name = nameMatch ? nameMatch[1].trim() : 'Kênh mới';
      const idMatch = line.match(/tvg-id="([^"]+)"/);
      const groupMatch = line.match(/group-title="([^"]+)"/);
      const countryMatch = line.match(/tvg-country="([^"]+)"/);

      currentInfo = {
        name,
        id: idMatch ? idMatch[1] : undefined,
        group: groupMatch ? groupMatch[1] : undefined,
        country: countryMatch ? countryMatch[1] : undefined,
      };
    } else if (!line.startsWith('#') && (line.startsWith('http://') || line.startsWith('https://'))) {
      if (currentInfo) {
        const isVN = currentInfo.country?.toUpperCase() === 'VN' || currentInfo.group?.toLowerCase().includes('vietnam');
        results.push({
          id: currentInfo.id || `custom-${Date.now()}-${results.length}`,
          name: currentInfo.name,
          streamUrl: line,
          defaultMode: 'hls',
          country: isVN ? 'VN' : 'GL',
          category: 'news',
          resolution: 'Auto',
          license: 'Kênh nhập người dùng',
          description: `Kênh phát trực tuyến từ danh sách M3U: ${currentInfo.name}`,
          schedule: [{ time: '00:00', title: 'Đang phát sóng trực tiếp' }],
        });
        currentInfo = null;
      }
    }
  }

  return results;
}

export function downloadFile(filename: string, content: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

